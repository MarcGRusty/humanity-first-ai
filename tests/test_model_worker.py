"""Our real model runs as the AI process behind the guardian, inside the sandbox."""

import pytest

torch = pytest.importorskip("torch")

from conftest import ScriptedPerson  # noqa: E402
from hfai.guardian.audit import verify_file  # noqa: E402
from hfai.guardian.core import Guardian  # noqa: E402
from hfai.model import ModelConfig, Transformer  # noqa: E402
from hfai.tokenizer import train  # noqa: E402
from hfai.training.checkpoint import save_weights  # noqa: E402


@pytest.fixture(scope="module")
def tiny_model_files(tmp_path_factory):
    root = tmp_path_factory.mktemp("model")
    tokenizer = train(["the sun rose over the quiet hills and the birds began to sing. " * 50], 300)
    tokenizer.save(root / "tok.json")
    torch.manual_seed(0)
    model = Transformer(ModelConfig(vocab_size=tokenizer.vocab_size, d_model=32, n_layers=2, n_heads=2, max_seq_len=64))
    save_weights(model, model.config.to_dict(), tokenizer.fingerprint, root / "model.pt")
    return root


def test_real_model_answers_through_the_guardian(tiny_model_files, tmp_path):
    person = ScriptedPerson()
    guardian = Guardian(tmp_path / "data", person,
                        ["-m", "hfai.worker.model", str(tiny_model_files / "model.pt"), str(tiny_model_files / "tok.json"), "12"],
                        label="AI-generated by a small model; may be wrong", timeout=120)
    guardian.start()
    turn = guardian.handle("the sun rose")
    guardian.close()
    assert isinstance(turn.text, str)
    assert turn.outcomes == ()  # the base model never proposes actions
    assert person.asked == []
    assert verify_file(tmp_path / "data" / "audit.log").ok


def test_mismatched_tokenizer_is_refused(tiny_model_files, tmp_path):
    other = train(["completely different text for another tokenizer " * 30], 290)
    other.save(tmp_path / "other.json")
    guardian = Guardian(tmp_path / "data", ScriptedPerson(),
                        ["-m", "hfai.worker.model", str(tiny_model_files / "model.pt"), str(tmp_path / "other.json")],
                        timeout=60)
    guardian.start()
    with pytest.raises(Exception, match="exited"):
        guardian.handle("hello")
    guardian.close()
