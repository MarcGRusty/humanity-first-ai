"""The real AI process: our trained model, running behind the guardian.

Usage (started by the guardian, inside the sandbox):
    python -m hfai.worker.model WEIGHTS TOKENIZER [MAX_NEW_TOKENS]

What it does, honestly: it continues the person's text with text in the style
it learned. It is a small base model, so it does not follow instructions or
answer questions reliably, and it never proposes actions (it cannot produce
them dependably). Its replies are labelled AI-generated by the guardian.

It only reads its weights and tokenizer, writes nothing, and uses no network.
"""

from __future__ import annotations

import sys

from hfai.worker.protocol import encode, install_network_guard, parse_request


def main(argv: list[str]) -> int:
    install_network_guard()
    import torch

    from hfai.tokenizer import Tokenizer
    from hfai.training.checkpoint import load_model

    weights, tokenizer_path = argv[0], argv[1]
    max_new = int(argv[2]) if len(argv) > 2 else 60
    torch.set_num_threads(2)
    tokenizer = Tokenizer.load(tokenizer_path)
    model, meta = load_model(weights)
    if meta["tokenizer_fingerprint"] != tokenizer.fingerprint:
        print("tokenizer does not match the weights", file=sys.stderr)
        return 2
    model.eval()
    eot = tokenizer.token_id("<|endoftext|>")
    limit = model.config.max_seq_len - max_new

    for line in sys.stdin:
        request = parse_request(line)
        if request["type"] == "shutdown":
            return 0
        ids = tokenizer.encode(request["message"])[-limit:] or [eot]
        generator = torch.Generator().manual_seed(request["id"])
        with torch.no_grad():
            out = model.generate(torch.tensor([ids]), max_new, temperature=0.8, top_k=50, stop_token=eot, generator=generator)
        new = [t for t in out[0, len(ids):].tolist() if t != eot]
        sys.stdout.write(encode({"id": request["id"], "text": tokenizer.decode(new), "proposals": []}))
        sys.stdout.flush()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
